/** Attacks that require an execution path are not applicable to a reporting-only agent. */
const EXECUTION_DEPENDENT: Attack['category'][] = [
  'transaction-mutation',
  'replay-expiry',
  'cross-chain',
  'network-boundary',
];

export function attacksForAgent(executionClass: ExecutionClass): Attack[] {
  if (executionClass !== 'REPORTING_ONLY') return ATTACKS_BASE;

  return ATTACKS_BASE.map((attack) =>
    EXECUTION_DEPENDENT.includes(attack.category) || attack.id === 'atk_runtime_compromise'
      ? {
          ...attack,
          applicable: false,
          notApplicableReason:
            'This agent has execution class NONE. There is no capability or executor path for this attack to target.',
          lastResult: null,
          lastRun: null,
          stoppingLayer: null,
          reasonCode: null,
          defencesExercised: [],
        }
      : attack,
  );
}
